// 随机获取犬只名称
export function getRandomDogName() {

    const index = Math.floor(
        Math.random() * DOG_NAMES.length
    );

    return DOG_NAMES[index];

}
// 抽取两个不同的初始名称（允许玩家手动改为同名）。
export function getStarterDogNames() {
    const first = getRandomDogName();
    const remaining = DOG_NAMES.filter(name => name !== first);
    return [first, remaining[Math.floor(Math.random() * remaining.length)]];
}
