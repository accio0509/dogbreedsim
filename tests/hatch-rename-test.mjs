import assert from 'node:assert/strict';
import {createAnimal} from '../engine/animal.js';
import {createEgg,INCUBATION_MS} from '../engine/egg.js';
import {claimEgg} from '../engine/breedingLifecycle.js';
import {renderHatchlingPreview} from '../ui/incubationRoom.js';
import {renderAnimalDetail} from '../ui/animalView.js';
import {createGameState,gameState,renameAnimal} from '../storage/state.js';
import {migrateSave} from '../storage/save.js';
const now=Date.now();
const mother=createAnimal({id:'M',breedId:'chihuahua',sex:'female',stage:'adult',name:'母犬'});
const father=createAnimal({id:'F',breedId:'chihuahua',sex:'male',stage:'adult',name:'父犬'});
const records={M:structuredClone(mother),F:structuredClone(father)};
const egg=createEgg({eggId:'E',offspringId:'P',mother,father,pedigreeRecords:records,now});
const original=JSON.stringify(egg);
const html=renderHatchlingPreview(egg,records);
assert.equal(renderHatchlingPreview(egg,records),html);
assert.equal(JSON.stringify(egg),original);
for(const text of ['新生幼犬','基本信息','外貌性状','实际能力','查看完整基因型','血统信息','母犬','父犬'])assert.ok(html.includes(text),text);
assert.ok(!html.includes('rename-animal')&&!html.includes('move-animal'));
const state={animals:[mother,father],eggs:[egg],pedigreeRecords:records};
const result=claimEgg({state,eggId:'E',name:'幼犬',now:now+INCUBATION_MS,persist:()=>true});
assert.ok(result.success,result.message);
assert.equal(html,renderAnimalDetail({...result.puppy,name:'新生幼犬'},{readOnly:true,previewLocation:'孵化室待领取',pedigreeRecords:records,showGenotype:true,actualStatsOnly:true}));
const reward=createAnimal({id:'R',breedId:'corgi',stage:'puppy',source:'competition'});
const rewardEgg={source:'competition',offspringData:reward,motherId:null,fatherId:null};
assert.ok(renderHatchlingPreview(rewardEgg).includes('实际能力'));
Object.assign(gameState,createGameState());
const puppy=result.puppy;gameState.activeAnimals={P:puppy,M:mother,F:father};gameState.pedigreeRecords=structuredClone(state.pedigreeRecords);
gameState.incubationTasks=[JSON.parse(original)];gameState.competitionRecords=[{animalId:'P',name:'幼犬'}];
const saved=structuredClone(puppy);for(const name of ['第一次','第二次','第三次']){assert.ok(renameAnimal('P',name).success);assert.equal(gameState.pedigreeRecords.P.name,name);assert.equal(gameState.competitionRecords[0].name,name);}
assert.deepEqual({...puppy,name:saved.name},saved);assert.ok(renameAnimal('M','新母犬').success);assert.equal(gameState.incubationTasks[0].motherName,'新母犬');assert.ok(renameAnimal('F','新父犬').success);assert.equal(gameState.incubationTasks[0].fatherName,'新父犬');
for(const name of ['',null,'犬'.repeat(21),'a\nb'])assert.equal(renameAnimal('P',name).success,false);
puppy.source='rental';assert.equal(renameAnimal('P','禁止').success,false);
const old=createGameState();old.version='1.0.2';assert.equal(migrateSave(old).version,'1.0.5');
console.log('V1.0.4 hatch preview, repeated rename, identity, parent names, rental and migration checks passed');
